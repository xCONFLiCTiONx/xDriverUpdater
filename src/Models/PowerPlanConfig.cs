namespace xDriverUpdater.Models;

public enum PresetKind
{
    SmartDevAi,
    MaxPerformance,
    CoolAndQuiet,
    Custom
}

public sealed class PowerPlanConfig
{
    public PresetKind Preset { get; set; } = PresetKind.SmartDevAi;
    public string PlanName { get; set; } = "xPowerPlan — Smart Dev & AI";
    public string PlanDescription { get; set; } = "Hardware-tuned plan generated by xSecurityCenter (zero background overhead).";
    public bool ReuseSingleManagedPlan { get; set; } = true;
    public bool UnhideUsefulAdvancedSettings { get; set; } = true;
    public bool AutoBackupPreviousPlan { get; set; } = false;

    // Sleep & Display (xTaskForge-compatible)
    public int DisplayOffMinutes { get; set; } = 10;   // 0 = Never
    public int SleepAfterMinutes { get; set; } = 15;   // 0 = Never
    public int HibernateAfterMinutes { get; set; } = 0; // 0 = Never (protects SSD TBW)
    public bool RespectMediaKeepAwake { get; set; } = true; // AllowSystemRequired + AllowDisplayRequired
    public int WakeTimersMode { get; set; } = 2;       // 0=Disable, 1=Enable, 2=Important Only
    public bool RequirePasswordOnWakeup { get; set; } = true;
    public bool AllowHybridSleep { get; set; } = false;

    // CPU (AMD Ryzen / CPPC2 aware)
    public int MinProcessorState { get; set; } = 5;    // 0..100%
    public int MaxProcessorState { get; set; } = 100;  // 0..100%
    public int BoostMode { get; set; } = 4;            // 0=Disabled, 1=Enabled, 2=Aggressive, 3=Eff.Enabled, 4=Eff.Aggressive
    public int BoostPolicy { get; set; } = 100;        // 0..100%
    public int EnergyPerfPreference { get; set; } = 20; // 0=MaxPerf, 100=MaxEco
    public int CoreParkingMinCores { get; set; } = 100; // 0..100% (100 = no parking)
    public int CoolingPolicy { get; set; } = 1;        // 0=Passive, 1=Active

    // GPU, PCIe & Storage (NVIDIA + NVMe + SATA + USB)
    public int PcieLinkStatePowerMgmt { get; set; } = 0; // 0=Off, 1=Moderate, 2=Maximum
    public int DiskTurnOffMinutes { get; set; } = 0;     // 0=Never
    public int AhciLinkPowerMgmt { get; set; } = 0;      // 0=Active, 1=HIPM, 2=HIPM+DIPM
    public int PrimaryNvmeIdleMs { get; set; } = 200;    // ms
    public int PrimaryNvmeLatTolMs { get; set; } = 15;   // ms
    public bool UsbSelectiveSuspend { get; set; } = false;
    public int Usb3LinkPowerMgmt { get; set; } = 0;      // 0=Off, 1=Minimum, 2=Moderate, 3=Maximum
    public int WirelessPowerSaving { get; set; } = 0;    // 0=Max Performance

    public PowerPlanConfig Clone() => (PowerPlanConfig)MemberwiseClone();
}
